def build_model_specs(random_state: int) -> list[ModelSpec]:
    logistic = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", RobustScaler()),
            (
                "model",
                LogisticRegression(
                    solver="liblinear",
                    class_weight="balanced",
                    max_iter=3000,
                    random_state=random_state,
                ),
            ),
        ]
    )

    tree = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            (
                "model",
                DecisionTreeClassifier(
                    class_weight="balanced",
                    random_state=random_state,
                ),
            ),
        ]
    )

    forest = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            (
                "model",
                RandomForestClassifier(
                    n_estimators=120,
                    class_weight="balanced_subsample",
                    n_jobs=1,
                    random_state=random_state,
                ),
            ),
        ]
    )

    return [
        ModelSpec(
            name="logistic_regression",
            estimator=logistic,
            param_grid={
                "model__C": [0.03, 0.1, 0.3, 1.0, 3.0],
            },
        ),
        ModelSpec(
            name="shallow_decision_tree",
            estimator=tree,
            param_grid={
                "model__max_depth": [2, 3, 4],
                "model__min_samples_leaf": [4, 7],
            },
        ),
        ModelSpec(
            name="restricted_random_forest",
            estimator=forest,
            param_grid={
                "model__max_depth": [2, 3],
                "model__min_samples_leaf": [4, 6],
                "model__max_features": ["sqrt"],
            },
        ),
    ]


def calculate_binary_metrics(
    y_true: np.ndarray | pd.Series,
    y_pred: np.ndarray | pd.Series,
    probabilities: Optional[np.ndarray | pd.Series] = None,
) -> dict[str, float]:
    y_true = np.asarray(y_true, dtype=int)
    y_pred = np.asarray(y_pred, dtype=int)

    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
    tn, fp, fn, tp = cm.ravel()

    metrics = {
        "n": int(len(y_true)),
        "true_negative": int(tn),
        "false_positive": int(fp),
        "false_negative": int(fn),
        "true_positive": int(tp),
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y_true, y_pred)),
        "precision_anomaly": float(
            precision_score(y_true, y_pred, zero_division=0)
        ),
        "recall_anomaly": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1_anomaly": float(f1_score(y_true, y_pred, zero_division=0)),
        "specificity_normal": float(tn / (tn + fp)) if (tn + fp) else np.nan,
        "normal_false_positive_rate": float(fp / (tn + fp))
        if (tn + fp)
        else np.nan,
    }

    if probabilities is not None and len(np.unique(y_true)) == 2:
        try:
            metrics["roc_auc"] = float(roc_auc_score(y_true, probabilities))
        except ValueError:
            metrics["roc_auc"] = np.nan
    else:
        metrics["roc_auc"] = np.nan

    return metrics


def select_probability_threshold(
    y_true: pd.Series | np.ndarray,
    probabilities: pd.Series | np.ndarray,
    max_normal_fpr: float,
) -> ThresholdResult:
    y_true = np.asarray(y_true, dtype=int)
    probabilities = np.asarray(probabilities, dtype=float)

    thresholds = np.round(np.arange(0.20, 0.801, 0.01), 2)
    candidates: list[ThresholdResult] = []

    for threshold in thresholds:
        predicted = (probabilities >= threshold).astype(int)
        metrics = calculate_binary_metrics(y_true, predicted, probabilities)
        fpr = metrics["normal_false_positive_rate"]
        combined = 0.50 * metrics["balanced_accuracy"] + 0.50 * metrics["f1_anomaly"]

        # Prefer thresholds satisfying the requested FPR limit. If none do,
        # penalise excess false positives smoothly instead of failing.
        penalty = max(0.0, fpr - max_normal_fpr)
        score = combined - 0.75 * penalty

        candidates.append(
            ThresholdResult(
                threshold=float(threshold),
                score=float(score),
                balanced_accuracy=float(metrics["balanced_accuracy"]),
                f1=float(metrics["f1_anomaly"]),
                recall=float(metrics["recall_anomaly"]),
                specificity=float(metrics["specificity_normal"]),
                normal_false_positive_rate=float(fpr),
            )
        )

    feasible = [
        candidate
        for candidate in candidates
        if candidate.normal_false_positive_rate <= max_normal_fpr
    ]
    pool = feasible if feasible else candidates

    # Maximise combined performance, then recall, then choose the threshold
    # closest to 0.5 to reduce unstable extreme thresholds.
    best = max(
        pool,
        key=lambda item: (
            item.score,
            item.balanced_accuracy,
            item.f1,
            item.recall,
            -abs(item.threshold - 0.5),
        ),
    )
    return best


def make_inner_cv(
    y: pd.Series,
    requested_splits: int,
    random_state: int,
) -> StratifiedKFold:
    minimum_class_count = int(y.value_counts().min())
    n_splits = max(2, min(requested_splits, minimum_class_count))
    return StratifiedKFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=random_state,
    )


def tune_model_and_threshold(
    spec: ModelSpec,
    X_train: pd.DataFrame,
    y_train: pd.Series,
    inner_splits: int,
    random_state: int,
    max_normal_fpr: float,
) -> tuple[BaseEstimator, dict[str, Any], ThresholdResult]:
    inner_cv = make_inner_cv(y_train, inner_splits, random_state)

    search = GridSearchCV(
        estimator=clone(spec.estimator),
        param_grid=spec.param_grid,
        scoring="roc_auc",
        cv=inner_cv,
        n_jobs=1,
        refit=True,
        error_score="raise",
    )
    search.fit(X_train, y_train)

    best_estimator = search.best_estimator_

    # Out-of-fold probabilities on the outer training data are used to tune
    # the classification threshold. The outer test fold remains untouched.
    oof_probabilities = cross_val_predict(
        clone(best_estimator),
        X_train,
        y_train,
        cv=inner_cv,
        method="predict_proba",
        n_jobs=1,
    )[:, 1]

    threshold_result = select_probability_threshold(
        y_true=y_train,
        probabilities=oof_probabilities,
        max_normal_fpr=max_normal_fpr,
    )

    best_estimator.fit(X_train, y_train)
    return best_estimator, search.best_params_, threshold_result


