def numeric_summary(
    group: pd.DataFrame,
    columns: list[str],
    prefix: str,
) -> dict[str, float]:
    output: dict[str, float] = {}
    for column in columns:
        if column not in group.columns:
            continue
        values = pd.to_numeric(group[column], errors="coerce").dropna()
        clean_name = column.replace("_max", "").replace("_median", "")
        if values.empty:
            output[f"{prefix}_{clean_name}_mean"] = 0.0
            output[f"{prefix}_{clean_name}_max"] = 0.0
            continue
        output[f"{prefix}_{clean_name}_mean"] = float(values.mean())
        output[f"{prefix}_{clean_name}_max"] = float(values.max())
    return output


def union_duration_by_event(
    group: pd.DataFrame,
    event_start: pd.Timestamp,
    event_end: pd.Timestamp,
    start_column: str = "segment_start",
    end_column: str = "segment_end",
) -> float:
    intervals: list[tuple[pd.Timestamp, pd.Timestamp]] = []
    for _, row in group.iterrows():
        clipped = clip_interval(
            row[start_column], row[end_column], event_start, event_end
        )
        if clipped is not None:
            intervals.append(clipped)
    return interval_hours(merge_intervals(intervals))


def aggregate_raw_segments(
    raw: pd.DataFrame,
    event_bounds: pd.DataFrame,
) -> pd.DataFrame:
    if raw.empty:
        return pd.DataFrame({"event_id": event_bounds["event_id"]})

    bounds = event_bounds.set_index("event_id")
    rows: list[dict[str, Any]] = []

    for event_id, group in raw.groupby("event_id", sort=False):
        if event_id not in bounds.index:
            continue

        event_start = pd.Timestamp(bounds.loc[event_id, "metadata_start"])
        event_end = pd.Timestamp(bounds.loc[event_id, "metadata_end"])
        event_hours = max(
            float(bounds.loc[event_id, "event_duration_hours"]), 1e-9
        )

        result: dict[str, Any] = {"event_id": event_id}

        detector = group.get("detector", pd.Series("", index=group.index)).astype(str)
        short = group.loc[detector == "short_standstill"].copy()
        persistent = group.loc[detector == "persistent_system_state"].copy()
        localized = group.loc[
            detector == "localized_persistent_subsystem_state"
        ].copy()

        if not localized.empty and "include_in_final" in localized.columns:
            confirmed_localized = localized.loc[localized["include_in_final"]].copy()
            rejected_localized = localized.loc[~localized["include_in_final"]].copy()
        else:
            confirmed_localized = pd.DataFrame(columns=localized.columns)
            rejected_localized = localized.copy()

        result["raw_short_segment_count"] = int(len(short))
        result["raw_persistent_segment_count"] = int(len(persistent))
        result["raw_confirmed_localized_count"] = int(len(confirmed_localized))
        result["raw_rejected_localized_count"] = int(len(rejected_localized))

        result.update(
            numeric_summary(
                short,
                [
                    "duration_minutes",
                    "detector_score_max",
                    "abnormal_fraction_max",
                    "power_dip_signal_count_max",
                    "power_recovery_signal_count_max",
                    "power_variability_signal_count_max",
                    "power_dip_score_max",
                    "power_recovery_score_max",
                    "power_variability_score_max",
                ],
                "raw_short",
            )
        )

        if not short.empty:
            required = np.ceil(
                0.75
                * pd.to_numeric(short.get("power_signal_count", 0), errors="coerce")
                .fillna(0)
            )
            required = np.maximum(required, 1)
            recovery_count = pd.to_numeric(
                short.get("power_recovery_signal_count_max", 0), errors="coerce"
            ).fillna(0)
            variability_count = pd.to_numeric(
                short.get("power_variability_signal_count_max", 0), errors="coerce"
            ).fillna(0)
            result["raw_short_direct_recovery_fraction"] = float(
                (recovery_count >= required).mean()
            )
            result["raw_short_variability_support_fraction"] = float(
                (variability_count >= required).mean()
            )
        else:
            result["raw_short_direct_recovery_fraction"] = 0.0
            result["raw_short_variability_support_fraction"] = 0.0

        result.update(
            numeric_summary(
                persistent,
                [
                    "duration_minutes",
                    "detector_score_max",
                    "abnormal_fraction_max",
                    "mean_active_signal_count",
                    "max_active_signal_count",
                ],
                "raw_persistent",
            )
        )

        for local_name, local_group in [
            ("confirmed_localized", confirmed_localized),
            ("rejected_localized", rejected_localized),
        ]:
            result.update(
                numeric_summary(
                    local_group,
                    [
                        "duration_minutes",
                        "detector_score_max",
                        "abnormal_fraction_max",
                        "dominant_signal_count",
                        "mean_active_signal_count",
                        "max_active_signal_count",
                        "mean_stable_signal_count",
                        "max_stable_signal_count",
                        "mean_sensor_set_overlap",
                        "long_power_dip_signal_count",
                        "long_power_recovery_signal_count",
                        "long_power_drop_ratio_median",
                        "long_power_recovery_ratio_median",
                        "boundary_power_dip_signal_count_max",
                        "boundary_power_recovery_signal_count_max",
                    ],
                    local_name,
                )
            )

            union_hours = union_duration_by_event(
                local_group, event_start, event_end
            )
            result[f"{local_name}_union_hours"] = union_hours
            result[f"{local_name}_coverage_fraction"] = min(
                1.0, union_hours / event_hours
            )

        if not rejected_localized.empty:
            rejection_reason = rejected_localized.get(
                "rejection_reason", pd.Series("", index=rejected_localized.index)
            ).fillna("").astype(str)
            result["rejected_missing_start_count"] = int(
                (rejection_reason == "missing_start_power_dip").sum()
            )
            result["rejected_missing_end_count"] = int(
                (rejection_reason == "missing_end_power_recovery").sum()
            )
            result["rejected_missing_both_count"] = int(
                (
                    rejection_reason
                    == "missing_start_power_dip_and_end_power_recovery"
                ).sum()
            )
            result["rejected_power_unavailable_count"] = int(
                (rejection_reason == "power_evidence_unavailable").sum()
            )

            if "power_dip_near_start" in rejected_localized.columns:
                result["rejected_start_dip_fraction"] = float(
                    rejected_localized["power_dip_near_start"].mean()
                )
            else:
                result["rejected_start_dip_fraction"] = 0.0

            if "power_recovery_near_end" in rejected_localized.columns:
                result["rejected_end_recovery_fraction"] = float(
                    rejected_localized["power_recovery_near_end"].mean()
                )
            else:
                result["rejected_end_recovery_fraction"] = 0.0
        else:
            for column in [
                "rejected_missing_start_count",
                "rejected_missing_end_count",
                "rejected_missing_both_count",
                "rejected_power_unavailable_count",
            ]:
                result[column] = 0
            result["rejected_start_dip_fraction"] = 0.0
            result["rejected_end_recovery_fraction"] = 0.0

        rows.append(result)

    aggregated = pd.DataFrame(rows)
    all_events = event_bounds[["event_id"]].drop_duplicates()
    return all_events.merge(aggregated, on="event_id", how="left").fillna(0.0)


