def create_model_dataset(
    feature_table: pd.DataFrame,
    raw_segments: pd.DataFrame,
    timeline: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.Series, pd.DataFrame, list[str]]:
    base = feature_table.copy()
    event_bounds = base[
        [
            "event_id",
            "metadata_start",
            "metadata_end",
            "event_duration_hours",
            "event_duration_days",
        ]
    ].copy()

    raw_features = aggregate_raw_segments(raw_segments, event_bounds)
    timeline_features = aggregate_timeline(timeline, event_bounds)

    data = base.merge(raw_features, on="event_id", how="left")
    data = data.merge(timeline_features, on="event_id", how="left")

    # Rates and coverage fractions use duration only as a denominator. The raw
    # duration columns are later excluded from X.
    event_hours = pd.to_numeric(data["event_duration_hours"], errors="coerce").fillna(0.0)
    event_days = pd.to_numeric(data["event_duration_days"], errors="coerce").fillna(0.0)

    data["persistent_coverage_fraction"] = safe_divide(
        data.get("total_persistent_hours", 0), event_hours
    ).clip(0, 1)
    data["confirmed_localized_coverage_fraction"] = safe_divide(
        data.get("total_confirmed_localized_hours", 0), event_hours
    ).clip(0, 1)
    data["rejected_localized_feature_coverage_fraction"] = safe_divide(
        data.get("total_rejected_localized_hours", 0), event_hours
    ).clip(0, 1)
    data["strong_cluster_rate_per_day"] = safe_divide(
        data.get("strong_cluster_count", 0), event_days
    )
    data["weak_cluster_rate_per_day"] = safe_divide(
        data.get("weak_cluster_count", 0), event_days
    )
    data["persistent_segment_rate_per_day"] = safe_divide(
        data.get("persistent_segment_count", 0), event_days
    )
    data["rejected_localized_rate_per_day"] = safe_divide(
        data.get("rejected_localized_candidate_count", 0), event_days
    )

    short_count = pd.to_numeric(
        data.get("short_episode_count", 0), errors="coerce"
    ).fillna(0.0)
    data["direct_recovery_short_ratio"] = safe_divide(
        data.get("direct_recovery_short_episode_count", 0), short_count
    )
    data["variability_only_short_ratio"] = safe_divide(
        data.get("variability_only_short_episode_count", 0), short_count
    )

    # Log transforms reduce domination by a few extremely long events while
    # retaining the information contained in duration/count features.
    log_candidates = [
        "short_episode_count",
        "max_short_count_2h",
        "max_short_count_24h",
        "weak_cluster_count",
        "strong_cluster_count",
        "persistent_segment_count",
        "max_persistent_hours",
        "total_persistent_hours",
        "confirmed_localized_segment_count",
        "max_confirmed_localized_hours",
        "total_confirmed_localized_hours",
        "rejected_localized_candidate_count",
        "max_rejected_localized_hours",
        "total_rejected_localized_hours",
        "raw_short_segment_count",
        "raw_persistent_segment_count",
        "raw_confirmed_localized_count",
        "raw_rejected_localized_count",
        "rejected_localized_union_hours",
        "confirmed_localized_union_hours",
    ]
    for column in log_candidates:
        if column in data.columns:
            values = pd.to_numeric(data[column], errors="coerce").fillna(0.0)
            data[f"log1p_{column}"] = np.log1p(values.clip(lower=0.0))

    y = data["metadata_label"].map(TARGET_MAP).astype(int)

    # Convert booleans to 0/1 before selecting numeric columns.
    for column in data.columns:
        if pd.api.types.is_bool_dtype(data[column]):
            data[column] = data[column].astype(int)
        elif data[column].dtype == object:
            lower_values = data[column].dropna().astype(str).str.lower().unique()
            if len(lower_values) > 0 and set(lower_values).issubset(TRUE_TEXT | {"false", "0", "no", "n", "f"}):
                data[column] = to_bool_series(data[column]).astype(int)

    candidate_columns = [
        column
        for column in MODEL_FEATURE_COLUMNS
        if column in data.columns
        and column not in LEAKAGE_OR_ID_COLUMNS
        and pd.api.types.is_numeric_dtype(data[column])
    ]

    # Remove all-empty and constant features. This is done before CV only for
    # deterministic structural columns, not using label information.
    X = data[candidate_columns].apply(pd.to_numeric, errors="coerce")
    all_empty = X.columns[X.isna().all()].tolist()
    X = X.drop(columns=all_empty)
    constant = [
        column
        for column in X.columns
        if X[column].nunique(dropna=True) <= 1
    ]
    X = X.drop(columns=constant)

    if X.empty:
        raise ValueError("No usable numeric event-level features were created.")

    metadata = data[
        ["event_id", "metadata_label", "metadata_start", "metadata_end"]
    ].copy()
    excluded_structural = all_empty + constant
    return X, y, metadata, excluded_structural


