# 14. MAIN
# =============================================================================

def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    if args.cv_splits < 2 or args.inner_splits < 2 or args.cv_repeats < 1:
        parser.error("CV splits must be >=2 and repeats must be >=1.")
    if not 0 < args.max_normal_fpr < 1:
        parser.error("--max-normal-fpr must be in (0, 1).")
    if not 0 < args.time_test_fraction < 0.5:
        parser.error("--time-test-fraction must be in (0, 0.5).")

    args.output_dir.mkdir(parents=True, exist_ok=True)

    features_path = resolve_input_file(
        args.input_dir,
        args.features_file,
        "all_events_event_level_features.csv",
        "all_events_event_level_features*.csv",
    )
    raw_path = resolve_input_file(
        args.input_dir,
        args.raw_segments_file,
        "all_events_detected_segments_raw.csv",
        "all_events_detected_segments_raw*.csv",
    )
    timeline_path = resolve_input_file(
        args.input_dir,
        args.timeline_segments_file,
        "all_events_detected_segments.csv",
        "all_events_detected_segments(*).csv",
        required=False,
    )
    baseline_path = resolve_input_file(
        args.input_dir,
        args.baseline_decisions_file,
        "all_events_event_level_decisions.csv",
        "all_events_event_level_decisions*.csv",
        required=False,
    )

    print(f"[INPUT] Features: {features_path}")
    print(f"[INPUT] Raw segments: {raw_path}")
    print(f"[INPUT] Timeline: {timeline_path}")
    print(f"[INPUT] Baseline decisions: {baseline_path}")

    feature_table = load_feature_table(features_path)
    raw_segments = load_segment_table(raw_path)
    timeline = load_timeline_table(timeline_path)

    X, y, metadata, excluded_structural = create_model_dataset(
        feature_table=feature_table,
        raw_segments=raw_segments,
        timeline=timeline,
    )

    print(
        f"[DATA] Events={len(X)}, features={X.shape[1]}, "
        f"normal={(y == 0).sum()}, anomaly={(y == 1).sum()}"
    )

    # Save the exact model matrix for audit and reproducibility.
    model_matrix = pd.concat([metadata.reset_index(drop=True), X.reset_index(drop=True)], axis=1)
    model_matrix["target_binary"] = y.to_numpy()
    model_matrix.to_csv(args.output_dir / "ml_event_feature_matrix.csv", index=False)

    specs = build_model_specs(args.random_state)
    fold_metrics, repeated_predictions, comparison = run_repeated_nested_cv(
        X=X,
        y=y,
        metadata=metadata,
        specs=specs,
        cv_splits=args.cv_splits,
        cv_repeats=args.cv_repeats,
        inner_splits=args.inner_splits,
        random_state=args.random_state,
        max_normal_fpr=args.max_normal_fpr,
    )

    aggregated_predictions = aggregate_repeated_predictions(repeated_predictions)
    selected_model_name = select_final_model_name(
        comparison,
        args.interpretability_tolerance,
    )
    selected_spec = next(spec for spec in specs if spec.name == selected_model_name)

    selected_predictions = aggregated_predictions.loc[
        aggregated_predictions["model"] == selected_model_name
    ].copy()
    selected_metrics = calculate_binary_metrics(
        selected_predictions["actual_binary"],
        selected_predictions["predicted_binary"],
        selected_predictions["mean_anomaly_probability"],
    )
    selected_metrics["selected_model"] = selected_model_name
    selected_metrics["evaluation_type"] = "aggregated_repeated_nested_cv"

    baseline_metrics = evaluate_rule_baseline(baseline_path)
    if baseline_metrics is not None:
        selected_metrics["rule_baseline"] = baseline_metrics

    fold_metrics.to_csv(args.output_dir / "ml_outer_fold_metrics.csv", index=False)
    repeated_predictions.to_csv(
        args.output_dir / "ml_repeated_cv_predictions.csv", index=False
    )
    comparison.to_csv(args.output_dir / "ml_model_comparison.csv", index=False)
    aggregated_predictions.to_csv(
        args.output_dir / "ml_event_predictions_all_models.csv", index=False
    )
    selected_predictions.to_csv(
        args.output_dir / "ml_event_predictions.csv", index=False
    )
    write_json(
        args.output_dir / "ml_selected_model_metrics.json",
        selected_metrics,
    )

    selected_cm = confusion_matrix(
        selected_predictions["actual_binary"],
        selected_predictions["predicted_binary"],
        labels=[0, 1],
    )
    pd.DataFrame(
        selected_cm,
        index=["actual_normal", "actual_anomaly"],
        columns=["predicted_normal", "predicted_anomaly"],
    ).to_csv(args.output_dir / "ml_selected_model_confusion_matrix.csv")

    # Chronological holdout using only earlier events for training.
    time_predictions, time_metrics = run_time_holdout(
        spec=selected_spec,
        X=X,
        y=y,
        metadata=metadata,
        test_fraction=args.time_test_fraction,
        inner_splits=args.inner_splits,
        random_state=args.random_state + 999,
        max_normal_fpr=args.max_normal_fpr,
    )
    time_predictions.to_csv(
        args.output_dir / "ml_time_holdout_predictions.csv", index=False
    )
    write_json(args.output_dir / "ml_time_holdout_metrics.json", time_metrics)

    # Final model fitted on all available labelled events.
    final_estimator, final_params, final_threshold_result, training_probabilities = (
        train_final_model(
            selected_spec=selected_spec,
            X=X,
            y=y,
            inner_splits=args.inner_splits,
            random_state=args.random_state + 2026,
            max_normal_fpr=args.max_normal_fpr,
        )
    )

    final_predictions = (training_probabilities >= final_threshold_result.threshold).astype(int)
    training_prediction_df = metadata.copy()
    training_prediction_df["actual_binary"] = y.to_numpy()
    training_prediction_df["anomaly_probability"] = training_probabilities
    training_prediction_df["threshold"] = final_threshold_result.threshold
    training_prediction_df["predicted_binary"] = final_predictions
    training_prediction_df["predicted_label"] = training_prediction_df["predicted_binary"].map(LABEL_MAP)
    training_prediction_df["prediction_correct"] = (
        training_prediction_df["actual_binary"]
        == training_prediction_df["predicted_binary"]
    )
    training_prediction_df.to_csv(
        args.output_dir / "final_model_training_predictions.csv", index=False
    )

    importance = extract_feature_importance(final_estimator, list(X.columns))
    importance.to_csv(args.output_dir / "ml_feature_importance.csv", index=False)

    explanations = build_event_explanations(
        estimator=final_estimator,
        X=X,
        metadata=metadata,
        probabilities=training_probabilities,
        threshold=final_threshold_result.threshold,
        importance=importance,
    )
    explanations.to_csv(args.output_dir / "ml_event_explanations.csv", index=False)

    model_bundle = {
        "model_name": selected_model_name,
        "estimator": final_estimator,
        "threshold": final_threshold_result.threshold,
        "feature_columns": list(X.columns),
        "target_map": TARGET_MAP,
        "best_params": final_params,
        "threshold_selection": final_threshold_result.__dict__,
        "training_event_count": int(len(X)),
        "training_class_counts": {
            "normal": int((y == 0).sum()),
            "anomaly": int((y == 1).sum()),
        },
    }
    joblib.dump(model_bundle, args.output_dir / "event_level_model.joblib")

    save_plots(comparison, selected_predictions, args.output_dir)

    manifest = {
        "features_file": features_path,
        "raw_segments_file": raw_path,
        "timeline_segments_file": timeline_path,
        "baseline_decisions_file": baseline_path,
        "output_dir": args.output_dir,
        "event_count": len(X),
        "feature_count": X.shape[1],
        "feature_columns": list(X.columns),
        "excluded_empty_or_constant_columns": excluded_structural,
        "selected_model": selected_model_name,
        "final_best_params": final_params,
        "final_threshold": final_threshold_result.__dict__,
        "cv_splits": args.cv_splits,
        "cv_repeats": args.cv_repeats,
        "inner_splits": args.inner_splits,
        "max_normal_fpr": args.max_normal_fpr,
        "interpretability_tolerance": args.interpretability_tolerance,
        "time_test_fraction": args.time_test_fraction,
        "random_state": args.random_state,
    }
    write_json(args.output_dir / "training_manifest.json", manifest)

    print("\n[DONE] Event-level ML training completed.")
    print(f"[SELECTED MODEL] {selected_model_name}")
    print(f"[FINAL THRESHOLD] {final_threshold_result.threshold:.2f}")
    print(
        "[AGGREGATED REPEATED-CV] "
        f"balanced_accuracy={selected_metrics['balanced_accuracy']:.3f}, "
        f"F1={selected_metrics['f1_anomaly']:.3f}, "
        f"recall={selected_metrics['recall_anomaly']:.3f}, "
        f"specificity={selected_metrics['specificity_normal']:.3f}, "
        f"normal_FPR={selected_metrics['normal_false_positive_rate']:.3f}"
    )
    print(f"[OUTPUT] {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
