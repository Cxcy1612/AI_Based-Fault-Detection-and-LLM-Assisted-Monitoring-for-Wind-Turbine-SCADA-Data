def extract_feature_importance(
    estimator: Pipeline,
    feature_names: list[str],
) -> pd.DataFrame:
    model = estimator.named_steps["model"]

    if hasattr(model, "coef_"):
        values = np.asarray(model.coef_[0], dtype=float)
        importance_type = "logistic_coefficient"
    elif hasattr(model, "feature_importances_"):
        values = np.asarray(model.feature_importances_, dtype=float)
        importance_type = "tree_feature_importance"
    else:
        return pd.DataFrame(
            columns=["feature", "importance", "absolute_importance", "importance_type"]
        )

    result = pd.DataFrame(
        {
            "feature": feature_names,
            "importance": values,
            "absolute_importance": np.abs(values),
            "importance_type": importance_type,
        }
    )
    return result.sort_values("absolute_importance", ascending=False).reset_index(drop=True)


def build_event_explanations(
    estimator: Pipeline,
    X: pd.DataFrame,
    metadata: pd.DataFrame,
    probabilities: np.ndarray,
    threshold: float,
    importance: pd.DataFrame,
    top_n: int = 5,
) -> pd.DataFrame:
    model = estimator.named_steps["model"]
    rows: list[dict[str, Any]] = []

    if hasattr(model, "coef_"):
        imputed = estimator.named_steps["imputer"].transform(X)
        scaled = estimator.named_steps["scaler"].transform(imputed)
        coefficients = np.asarray(model.coef_[0], dtype=float)
        contributions = scaled * coefficients

        for index in range(len(X)):
            contribution_row = contributions[index]
            positive_idx = np.argsort(contribution_row)[::-1][:top_n]
            negative_idx = np.argsort(contribution_row)[:top_n]

            positive = "; ".join(
                f"{X.columns[i]}={contribution_row[i]:+.3f}"
                for i in positive_idx
                if contribution_row[i] > 0
            )
            negative = "; ".join(
                f"{X.columns[i]}={contribution_row[i]:+.3f}"
                for i in negative_idx
                if contribution_row[i] < 0
            )

            predicted_binary = int(probabilities[index] >= threshold)
            rows.append(
                {
                    "event_id": metadata.iloc[index]["event_id"],
                    "actual_label": metadata.iloc[index]["metadata_label"],
                    "anomaly_probability": float(probabilities[index]),
                    "threshold": float(threshold),
                    "predicted_label": LABEL_MAP[predicted_binary],
                    "main_supporting_features": positive,
                    "main_opposing_features": negative,
                    "explanation_method": "logistic_local_contribution",
                }
            )
    else:
        global_top = "; ".join(
            importance.head(top_n)["feature"].astype(str).tolist()
        )
        for index in range(len(X)):
            predicted_binary = int(probabilities[index] >= threshold)
            rows.append(
                {
                    "event_id": metadata.iloc[index]["event_id"],
                    "actual_label": metadata.iloc[index]["metadata_label"],
                    "anomaly_probability": float(probabilities[index]),
                    "threshold": float(threshold),
                    "predicted_label": LABEL_MAP[predicted_binary],
                    "main_supporting_features": global_top,
                    "main_opposing_features": "",
                    "explanation_method": "global_tree_importance",
                }
            )

    return pd.DataFrame(rows)


def train_final_model(
    selected_spec: ModelSpec,
    X: pd.DataFrame,
    y: pd.Series,
    inner_splits: int,
    random_state: int,
    max_normal_fpr: float,
) -> tuple[Pipeline, dict[str, Any], ThresholdResult, np.ndarray]:
    estimator, best_params, threshold_result = tune_model_and_threshold(
        spec=selected_spec,
        X_train=X,
        y_train=y,
        inner_splits=inner_splits,
        random_state=random_state,
        max_normal_fpr=max_normal_fpr,
    )
    probabilities = estimator.predict_proba(X)[:, 1]
    return estimator, best_params, threshold_result, probabilities


# =============================================================================
# 10. CHRONOLOGICAL HOLDOUT
# =============================================================================

def run_time_holdout(
    spec: ModelSpec,
    X: pd.DataFrame,
    y: pd.Series,
    metadata: pd.DataFrame,
    test_fraction: float,
    inner_splits: int,
    random_state: int,
    max_normal_fpr: float,
) -> tuple[pd.DataFrame, dict[str, Any]]:
    order = np.argsort(pd.to_datetime(metadata["metadata_start"]).to_numpy())
    test_count = max(1, int(math.ceil(len(X) * test_fraction)))
    train_idx = order[:-test_count]
    test_idx = order[-test_count:]

    if len(train_idx) < 10 or y.iloc[train_idx].nunique() < 2:
        return pd.DataFrame(), {
            "status": "skipped",
            "reason": "Chronological training subset was too small or had one class.",
        }

    X_train = X.iloc[train_idx]
    y_train = y.iloc[train_idx]
    X_test = X.iloc[test_idx]
    y_test = y.iloc[test_idx]

    estimator, best_params, threshold_result = tune_model_and_threshold(
        spec=spec,
        X_train=X_train,
        y_train=y_train,
        inner_splits=inner_splits,
        random_state=random_state,
        max_normal_fpr=max_normal_fpr,
    )

    probabilities = estimator.predict_proba(X_test)[:, 1]
    predicted = (probabilities >= threshold_result.threshold).astype(int)
    metrics = calculate_binary_metrics(y_test, predicted, probabilities)
    metrics.update(
        {
            "status": "success",
            "train_events": int(len(train_idx)),
            "test_events": int(len(test_idx)),
            "threshold": threshold_result.threshold,
            "best_params": best_params,
            "training_start": metadata.iloc[train_idx]["metadata_start"].min(),
            "training_end": metadata.iloc[train_idx]["metadata_start"].max(),
            "test_start": metadata.iloc[test_idx]["metadata_start"].min(),
            "test_end": metadata.iloc[test_idx]["metadata_start"].max(),
        }
    )

    predictions = metadata.iloc[test_idx].copy().reset_index(drop=True)
    predictions["actual_binary"] = y_test.to_numpy()
    predictions["actual_label"] = predictions["actual_binary"].map(LABEL_MAP)
    predictions["anomaly_probability"] = probabilities
    predictions["threshold"] = threshold_result.threshold
    predictions["predicted_binary"] = predicted
    predictions["predicted_label"] = predictions["predicted_binary"].map(LABEL_MAP)
    predictions["prediction_correct"] = (
        predictions["actual_binary"] == predictions["predicted_binary"]
    )

    return predictions, metrics


# =============================================================================
# 11. BASELINE COMPARISON
# =============================================================================

def evaluate_rule_baseline(path: Optional[Path]) -> Optional[dict[str, Any]]:
    if path is None or not path.exists():
        return None
    df = pd.read_csv(path, low_memory=False)
    required = {"metadata_label", "binary_decision"}
    if not required.issubset(df.columns):
        return None

    actual = (
        df["metadata_label"].astype(str).str.lower().map(TARGET_MAP)
    )
    predicted = (
        df["binary_decision"].astype(str).str.lower().map(TARGET_MAP)
    )
    valid = actual.notna() & predicted.notna()
    if not valid.any():
        return None
    return calculate_binary_metrics(
        actual.loc[valid].astype(int),
        predicted.loc[valid].astype(int),
    )


