def aggregate_timeline(
    timeline: pd.DataFrame,
    event_bounds: pd.DataFrame,
) -> pd.DataFrame:
    if timeline.empty:
        return pd.DataFrame({"event_id": event_bounds["event_id"]})

    bounds = event_bounds.set_index("event_id")
    rows: list[dict[str, Any]] = []

    for event_id, group in timeline.groupby("event_id", sort=False):
        if event_id not in bounds.index:
            continue
        event_start = pd.Timestamp(bounds.loc[event_id, "metadata_start"])
        event_end = pd.Timestamp(bounds.loc[event_id, "metadata_end"])
        event_hours = max(
            float(bounds.loc[event_id, "event_duration_hours"]), 1e-9
        )

        result: dict[str, Any] = {"event_id": event_id}
        group = group.copy()
        group["duration_hours_clipped"] = group.apply(
            lambda row: (
                (clip_interval(row["event_start"], row["event_end"], event_start, event_end)[1]
                 - clip_interval(row["event_start"], row["event_end"], event_start, event_end)[0])
                .total_seconds()
                / 3600.0
                if clip_interval(
                    row["event_start"], row["event_end"], event_start, event_end
                )
                is not None
                else 0.0
            ),
            axis=1,
        )

        n_detectors = pd.to_numeric(group.get("n_detectors", 0), errors="coerce").fillna(0)
        overlap = group.loc[n_detectors >= 2]
        result["timeline_interval_count"] = int(len(group))
        result["timeline_multi_detector_interval_count"] = int(len(overlap))
        result["timeline_max_detector_count"] = float(n_detectors.max()) if len(group) else 0.0
        result["timeline_mean_detector_count"] = float(n_detectors.mean()) if len(group) else 0.0
        result["timeline_confirmed_union_hours"] = float(
            group["duration_hours_clipped"].sum()
        )
        result["timeline_confirmed_coverage_fraction"] = min(
            1.0, result["timeline_confirmed_union_hours"] / event_hours
        )
        result["timeline_multi_detector_hours"] = float(
            overlap["duration_hours_clipped"].sum()
        )
        result["timeline_multi_detector_coverage_fraction"] = min(
            1.0, result["timeline_multi_detector_hours"] / event_hours
        )

        for column in [
            "mean_smoothed_score",
            "mean_abnormal_fraction",
            "contained_short_standstill_count",
            "mean_short_standstill_fraction",
            "mean_intermittent_short_flag_density",
            "mean_persistent_system_fraction",
            "mean_localized_active_fraction",
            "mean_localized_stable_signal_count",
            "mean_localized_sensor_set_overlap",
            "localized_long_power_recovery_ratio_median",
            "localized_long_power_dip_signal_count_max",
            "localized_long_power_recovery_signal_count_max",
        ]:
            if column not in group.columns:
                continue
            values = pd.to_numeric(group[column], errors="coerce").dropna()
            result[f"timeline_{column}_mean"] = float(values.mean()) if not values.empty else 0.0
            result[f"timeline_{column}_max"] = float(values.max()) if not values.empty else 0.0

        rows.append(result)

    aggregated = pd.DataFrame(rows)
    all_events = event_bounds[["event_id"]].drop_duplicates()
    return all_events.merge(aggregated, on="event_id", how="left").fillna(0.0)


