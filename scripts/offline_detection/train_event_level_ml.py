def save_plots(
    comparison: pd.DataFrame,
    selected_predictions: pd.DataFrame,
    output_dir: Path,
) -> None:
    if not comparison.empty:
        fig, ax = plt.subplots(figsize=(9, 5))
        ordered = comparison.sort_values("mean_balanced_accuracy")
        ax.barh(ordered["model"], ordered["mean_balanced_accuracy"])
        ax.set_xlabel("Mean outer-fold balanced accuracy")
        ax.set_ylabel("Model")
        ax.set_title("Event-level model comparison")
        ax.set_xlim(0, 1)
        fig.tight_layout()
        fig.savefig(output_dir / "model_comparison_balanced_accuracy.png", dpi=160)
        plt.close(fig)

    if not selected_predictions.empty:
        actual = selected_predictions["actual_binary"].astype(int)
        predicted = selected_predictions["predicted_binary"].astype(int)
        cm = confusion_matrix(actual, predicted, labels=[0, 1])

        fig, ax = plt.subplots(figsize=(5.5, 5))
        image = ax.imshow(cm)
        ax.set_xticks([0, 1], labels=["normal", "anomaly"])
        ax.set_yticks([0, 1], labels=["normal", "anomaly"])
        ax.set_xlabel("Predicted")
        ax.set_ylabel("Actual")
        ax.set_title("Aggregated repeated-CV confusion matrix")
        for row in range(2):
            for col in range(2):
                ax.text(col, row, str(cm[row, col]), ha="center", va="center")
        fig.colorbar(image, ax=ax)
        fig.tight_layout()
        fig.savefig(output_dir / "selected_model_confusion_matrix.png", dpi=160)
        plt.close(fig)

        fig, ax = plt.subplots(figsize=(9, 5))
        for label, group in selected_predictions.groupby("actual_label"):
            ax.hist(
                group["mean_anomaly_probability"],
                bins=np.linspace(0, 1, 16),
                alpha=0.55,
                label=str(label),
            )
        ax.set_xlabel("Mean repeated-CV anomaly probability")
        ax.set_ylabel("Number of events")
        ax.set_title("Cross-validated event probability distribution")
        ax.legend()
        fig.tight_layout()
        fig.savefig(output_dir / "selected_model_probability_distribution.png", dpi=160)
        plt.close(fig)


