def load_feature_table(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path, low_memory=False)
    required = {
        "event_id",
        "metadata_label",
        "metadata_start",
        "metadata_end",
        "event_duration_hours",
        "event_duration_days",
    }
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(
            f"Feature table is missing required columns: {missing}. "
            f"Available columns: {list(df.columns)}"
        )

    df = df.copy()
    df["event_id"] = df["event_id"].map(normalise_event_id)
    df["metadata_label"] = (
        df["metadata_label"].astype(str).str.strip().str.lower()
    )
    df["metadata_start"] = pd.to_datetime(
        df["metadata_start"], errors="coerce"
    )
    df["metadata_end"] = pd.to_datetime(df["metadata_end"], errors="coerce")

    df = df.loc[df["metadata_label"].isin(TARGET_MAP)].copy()
    df = df.dropna(subset=["metadata_start", "metadata_end"])
    df = df.drop_duplicates(subset=["event_id"], keep="last")
    df = df.reset_index(drop=True)

    if df.empty:
        raise ValueError("No labelled normal/anomaly events remain after cleaning.")

    return df


def load_segment_table(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path, low_memory=False)
    if df.empty:
        return df

    required = {"event_id", "segment_start", "segment_end"}
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(f"Segment table {path.name} is missing: {missing}")

    df = df.copy()
    df["event_id"] = df["event_id"].map(normalise_event_id)
    df["segment_start"] = pd.to_datetime(df["segment_start"], errors="coerce")
    df["segment_end"] = pd.to_datetime(df["segment_end"], errors="coerce")
    df = df.dropna(subset=["segment_start", "segment_end"])
    df = df.loc[df["segment_end"] > df["segment_start"]].copy()

    for column in [
        "include_in_final",
        "power_confirmation_passed",
        "power_dip_near_start",
        "power_recovery_near_end",
        "long_power_recovery_confirmed",
        "power_evidence_available",
        "power_evidence_confirmed",
    ]:
        if column in df.columns:
            df[column] = to_bool_series(df[column])

    return df


