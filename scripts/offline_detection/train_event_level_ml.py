def run_repeated_nested_cv(
    X: pd.DataFrame,
    y: pd.Series,
    metadata: pd.DataFrame,
    specs: list[ModelSpec],
    cv_splits: int,
    cv_repeats: int,
    inner_splits: int,
    random_state: int,
    max_normal_fpr: float,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    minimum_class_count = int(y.value_counts().min())
    n_splits = max(2, min(cv_splits, minimum_class_count))

    outer_cv = RepeatedStratifiedKFold(
        n_splits=n_splits,
        n_repeats=cv_repeats,
        random_state=random_state,
    )

    fold_rows: list[dict[str, Any]] = []
    prediction_rows: list[dict[str, Any]] = []

    total_folds = n_splits * cv_repeats
    for spec in specs:
        print(f"[CV] Model: {spec.name}")
        for split_number, (train_idx, test_idx) in enumerate(
            outer_cv.split(X, y), start=1
        ):
            repeat_number = (split_number - 1) // n_splits + 1
            fold_number = (split_number - 1) % n_splits + 1

            X_train = X.iloc[train_idx]
            X_test = X.iloc[test_idx]
            y_train = y.iloc[train_idx]
            y_test = y.iloc[test_idx]

            seed = random_state + split_number * 100 + len(fold_rows)
            estimator, best_params, threshold_result = tune_model_and_threshold(
                spec=spec,
                X_train=X_train,
                y_train=y_train,
                inner_splits=inner_splits,
                random_state=seed,
                max_normal_fpr=max_normal_fpr,
            )

            probabilities = estimator.predict_proba(X_test)[:, 1]
            predicted = (probabilities >= threshold_result.threshold).astype(int)
            metrics = calculate_binary_metrics(y_test, predicted, probabilities)

            fold_rows.append(
                {
                    "model": spec.name,
                    "repeat": repeat_number,
                    "fold": fold_number,
                    "threshold": threshold_result.threshold,
                    "best_params": json.dumps(best_params, sort_keys=True),
                    **metrics,
                }
            )

            test_metadata = metadata.iloc[test_idx].reset_index(drop=True)
            for position in range(len(test_idx)):
                prediction_rows.append(
                    {
                        "model": spec.name,
                        "repeat": repeat_number,
                        "fold": fold_number,
                        "event_id": test_metadata.loc[position, "event_id"],
                        "metadata_start": test_metadata.loc[position, "metadata_start"],
                        "actual_label": LABEL_MAP[int(y_test.iloc[position])],
                        "actual_binary": int(y_test.iloc[position]),
                        "anomaly_probability": float(probabilities[position]),
                        "threshold": float(threshold_result.threshold),
                        "decision_margin": float(
                            probabilities[position] - threshold_result.threshold
                        ),
                        "predicted_binary": int(predicted[position]),
                        "predicted_label": LABEL_MAP[int(predicted[position])],
                    }
                )

            if split_number == 1 or split_number % max(1, n_splits) == 0:
                print(
                    f"  completed {split_number}/{total_folds} folds "
                    f"for {spec.name}"
                )

    fold_df = pd.DataFrame(fold_rows)
    repeated_predictions = pd.DataFrame(prediction_rows)

    comparison_rows: list[dict[str, Any]] = []
    metric_columns = [
        "accuracy",
        "balanced_accuracy",
        "precision_anomaly",
        "recall_anomaly",
        "f1_anomaly",
        "specificity_normal",
        "normal_false_positive_rate",
        "roc_auc",
        "threshold",
    ]

    for model_name, group in fold_df.groupby("model"):
        row: dict[str, Any] = {"model": model_name, "fold_count": len(group)}
        for metric in metric_columns:
            values = pd.to_numeric(group[metric], errors="coerce")
            row[f"mean_{metric}"] = float(values.mean())
            row[f"std_{metric}"] = float(values.std(ddof=1))
        comparison_rows.append(row)

    comparison = pd.DataFrame(comparison_rows).sort_values(
        ["mean_balanced_accuracy", "mean_f1_anomaly", "mean_roc_auc"],
        ascending=False,
    )

    return fold_df, repeated_predictions, comparison


def aggregate_repeated_predictions(
    repeated_predictions: pd.DataFrame,
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []

    for (model_name, event_id), group in repeated_predictions.groupby(
        ["model", "event_id"], sort=False
    ):
        mean_margin = float(group["decision_margin"].mean())
        predicted_binary = int(mean_margin >= 0.0)
        rows.append(
            {
                "model": model_name,
                "event_id": event_id,
                "metadata_start": group["metadata_start"].iloc[0],
                "actual_label": group["actual_label"].iloc[0],
                "actual_binary": int(group["actual_binary"].iloc[0]),
                "cv_prediction_count": int(len(group)),
                "mean_anomaly_probability": float(
                    group["anomaly_probability"].mean()
                ),
                "std_anomaly_probability": float(
                    group["anomaly_probability"].std(ddof=1)
                )
                if len(group) > 1
                else 0.0,
                "mean_threshold": float(group["threshold"].mean()),
                "mean_decision_margin": mean_margin,
                "anomaly_vote_fraction": float(
                    group["predicted_binary"].mean()
                ),
                "predicted_binary": predicted_binary,
                "predicted_label": LABEL_MAP[predicted_binary],
                "prediction_correct": bool(
                    predicted_binary == int(group["actual_binary"].iloc[0])
                ),
            }
        )

    return pd.DataFrame(rows)


def select_final_model_name(
    comparison: pd.DataFrame,
    interpretability_tolerance: float,
) -> str:
    if comparison.empty:
        raise ValueError("Model comparison is empty.")

    top_row = comparison.iloc[0]
    top_name = str(top_row["model"])
    top_score = float(top_row["mean_balanced_accuracy"])

    logistic_rows = comparison.loc[
        comparison["model"] == "logistic_regression"
    ]
    if not logistic_rows.empty:
        logistic_score = float(
            logistic_rows.iloc[0]["mean_balanced_accuracy"]
        )
        if top_score - logistic_score <= interpretability_tolerance:
            return "logistic_regression"

    return top_name


